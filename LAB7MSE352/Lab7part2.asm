ORG 0000H
	MAIN:
		MOV A, #0FEH
		LOOP:
			MOV P1, A
			ACALL DELAY_500MS
			RL A
			SJMP LOOP
	DELAY_500MS:
		MOV R2, #255
		DELAY_OUTER:
			MOV R1, #255
			DELAY_INNER:
				NOP
				DJNZ R1, DELAY_INNER
				DJNZ R2, DELAY_OUTER
				RET
	;LED_ON:
		;SETB ,P2
	;LED_OFF:
		;CLR ,P2
		;SJMP MAIN
	END